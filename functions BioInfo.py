# fourth function generate random DNA sequence
def generate_random_dna(size:int)->str:
  """
  function name >> generate_random_dna
  function param >> size
  fucntion return >> dna sequence
  """
  sequence_list = []
  nucleotides = ['A', 'G', 'C', 'T']
  for i in range(size):
    random_choice = random.choice(nucleotides)
    sequence_list.append(random_choice)
  sequence_str = "".join(sequence_list)
