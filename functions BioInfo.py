import random
# first function validate DNA sequence
def validate_sequence_dna(sequence:str):
  """
  function name >> validate_sequence
  function param >> sequence DNA
  """
  nucleotides = ['A', 'G', 'C', 'T'] # this is list of nucleotides A G C T
  for nucleotide in sequence:
    if nucleotide not in nucleotides:
      print("Invalid sequence!")
      return
  print("valid sequence!")

